String slug(String s) {
  var t = s.toLowerCase().trim().replaceAll(RegExp(r"[''`]"), '');
  t = t.replaceAll(RegExp(r'[^a-z0-9]+'), '-').replaceAll(RegExp(r'^-+|-+$'), '');
  if (t.isEmpty) t = 'word';
  return '$t.png';
}

String dq(String s) {
  var e = s.replaceAll('\\', '\\\\').replaceAll('\$', '\\\$\n'.trim());
  // fix above: escape dollar
  e = s.replaceAll('\\', '\\\\').replaceAll('\$', '\\\x24');
  if (e.contains("'")) {
    e = e.replaceAll('"', '\\"');
    return '"$e"';
  } else {
    e = e.replaceAll("'", "\\'");
    return "'$e'";
  }
}

