void main() {
  final inFile = File('lib/data/words.dart');
  final lines = inFile.readAsLinesSync();
  final re = RegExp(r"""Word\(english:\s*('[^']*'|"[^"]*")\s*,\s*uzbek:\s*('[^']*'|"[^"]*")\s*,\s*category:\s*('[^']*'|"[^"]*")\s*\)""");
  String unquote(String q) => q.substring(1, q.length - 1);

  final buf = StringBuffer();
  buf.writeln('// ignore_for_file: prefer_const_constructors');
  buf.writeln('// 🖼️ RASMLI TEST RO\'YXATI — barcha so\'zlar (avto-generatsiya)');
  buf.writeln('// Generator: dart tools/gen_picture_words.dart');
  buf.writeln('// Har bir so\'z emoji-rasm bilan ishlaydi.');
  buf.writeln('// Agar assets/picture_quiz/<slug>.png mavjud bo\'lsa — real foto ko\'rsatiladi,');
  buf.writeln('// bo\'lmasa — katta emoji ko\'rsatiladi. Shuning uchun test internet/rasmsiz ham ishlaydi.');
  buf.writeln('');
  buf.writeln('class PictureWord {');
  buf.writeln('  final String english;');
  buf.writeln('  final String uzbek;');
  buf.writeln('  final String imagePath;');
  buf.writeln('  final String emoji;');
  buf.writeln('  final String category;');
  buf.writeln('');
  buf.writeln('  const PictureWord({');
  buf.writeln('    required this.english,');
  buf.writeln('    required this.uzbek,');
  buf.writeln('    required this.imagePath,');
  buf.writeln('    required this.emoji,');
  buf.writeln('    required this.category,');
  buf.writeln('  });');
  buf.writeln('}');
  buf.writeln('');
  int count = 0;
  buf.writeln('/// Barcha so\'zlar rasmli testda — har safar 10 tasi tasodifiy tushadi.');
  buf.writeln('const List<PictureWord> pictureWords = [');

  for (final l in lines) {
    final m = re.firstMatch(l);
    if (m == null) continue;
    final eng = unquote(m.group(1)!);
    final uzb = unquote(m.group(2)!);
    final cat = unquote(m.group(3)!);
    final key = eng.toLowerCase().trim();
    final emoji = emojis[key] ?? '📝';
    final file = slug(eng);
    buf.writeln(
        "  PictureWord(english: ${dq(eng)}, uzbek: ${dq(uzb)}, imagePath: 'assets/picture_quiz/$file', emoji: '$emoji', category: ${dq(cat)}),");
    count++;
  }
  buf.writeln('];');
  File('lib/data/picture_words.dart').writeAsStringSync(buf.toString());
  print('WROTE $count picture words');
}
